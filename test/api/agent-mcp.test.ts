import { Remote, until } from './helpers.ts';

async function setup(t: any) {
  const dir = await mkdtemp(join(tmpdir(), 'agent-mcp-'));
  const backend = new Remote();
  const service = new ApiService({ database: join(dir, 'state.sqlite'), backend });
  const server = createAgentMcpServer(service);
  const [a, b] = InMemoryTransport.createLinkedPair();
  await server.connect(a);
  const client = new Client({ name: 'agent-test', version: '1' });
  await client.connect(b);
  t.after(async () => { await client.close(); await server.close(); service.close(); await rm(dir, { recursive: true, force: true }); });
  const call = async (name: string, args: any) => {
    const response = await client.callTool({ name, arguments: args });
    const content = response.content as any[];
    assert.equal(content.length, 1); assert.equal(content[0].type, 'text');
    return { ...JSON.parse(content[0].text), isError: response.isError };
  };
  return { backend, service, client, call };
}
test('agent MCP: discover, ask, continue and replay without a second generation', async t => {
  const { backend, client, call } = await setup(t);
  const { tools } = await client.listTools();
  assert.deepEqual(tools.map(tool => tool.name).sort(), ['ask_gemini_chat', 'get_gemini_result']);
  const args = { request_id: 'one', prompt: 'hello', wait_ms: 1000 };
  const first = await call('ask_gemini_chat', args);
  assert.equal(first.status, 'completed'); assert.equal(first.text, 'reply:hello');
  assert.equal((await call('ask_gemini_chat', args)).run_id, first.run_id);
  assert.equal(backend.generations.length, 1);
  assert.equal((await call('ask_gemini_chat', { ...args, prompt: 'changed' })).error, 'IDEMPOTENCY_CONFLICT');
  const second = await call('ask_gemini_chat', { request_id: 'two', prompt: 'continue', chat_id: first.chat_id, wait_ms: 1000 });
  assert.equal(second.text, 'reply:continue'); assert.equal(second.chat_id, first.chat_id);
  assert.deepEqual(backend.generations[1].parent, first.position);
  assert.equal((await call('get_gemini_result', { run_id: first.run_id, wait_ms: 0 })).text, first.text);
  const invalid = await client.callTool({ name: 'ask_gemini_chat', arguments: { ...args, connector: { id: 'anything' } } });
  assert.equal(invalid.isError, true); assert.equal(backend.generations.length, 2);
});
test('slow and uncertain answers keep their original run and recover only by history', async t => {
  const { backend, service, call } = await setup(t);
  let release!: () => void;
  backend.gate = new Promise<void>(resolve => { release = resolve; });
  backend.failAfterWrite = true;
  const args = { request_id: 'slow', prompt: 'slow hello', wait_ms: 0 };
  const first = await call('ask_gemini_chat', args);
  assert.equal(first.status, 'running');
  assert.equal((await call('ask_gemini_chat', args)).run_id, first.run_id);
  assert.equal((await call('get_gemini_result', { run_id: first.run_id, wait_ms: 0 })).status, 'running');
  release(); await until(() => service.getRun(first.run_id).status === 'uncertain');
  const recovered = await call('get_gemini_result', { run_id: first.run_id, wait_ms: 0 });
  assert.equal(recovered.status, 'completed'); assert.equal(recovered.text, 'reply:slow hello');
  assert.equal(backend.generations.length, 1);
});

test('failed history recovery returns the original run, corrected partial text and both errors',async t=>{
  const {backend,service,call}=await setup(t);
  let calls=0;
  backend.generate=async(_input,observe)=>{
    calls++;observe({type:'text.delta',delta:'broken link'});
    observe({type:'text.replace',text:'[project](https://example.com)'});
    observe({type:'text.delta',delta:'\nNext paragraph'});
    throw new ApiError('UPSTREAM_UNCERTAIN','HTTP_TRANSPORT_ERROR');
  };
  backend.recover=async()=>{throw new ApiError('UPSTREAM_HISTORY_REJECTED','Upstream history RPC 5, BardErrorInfo 1167');};
  const first=await call('ask_gemini_chat',{request_id:'partial',prompt:'fixture',wait_ms:1000});
  const r=await call('get_gemini_result',{run_id:first.run_id,wait_ms:0});
  assert.equal(r.isError,false);assert.equal(r.run_id,first.run_id);assert.equal(r.status,'uncertain');
  assert.equal(r.text,undefined);assert.equal(r.partial.complete,false);
  assert.equal(r.partial.text,'[project](https://example.com)\nNext paragraph');
  assert.equal(r.error.message,'HTTP_TRANSPORT_ERROR');assert.match(r.recovery_error.message,/1167/);
  assert.equal(service.getRun(r.run_id).partial?.text,r.partial.text);assert.equal(calls,1);
});

test('agent chooses a fixed chat mode; temporary retries, polling and continuation never fetch history', async t => {
  const { backend, service, client, call } = await setup(t);
  const tool = (await client.listTools()).tools.find(t => t.name === 'ask_gemini_chat')!;
  assert.match(tool.description!, /one-shot/); assert.match(tool.description!, /multi-turn/);
  backend.history = async () => { assert.fail('temporary history must stay local'); };
  backend.recover = async () => { assert.fail('temporary recovery must not query upstream'); };
  let release!: () => void;
  backend.gate = new Promise<void>(resolve => { release = resolve; });
  const args = { request_id: 'temporary-1', prompt: 'one shot', mode: 'temporary', wait_ms: 0 };
  const first = await call('ask_gemini_chat', args);
  assert.equal(first.mode, 'temporary'); assert.equal(first.status, 'running');
  assert.equal((await call('ask_gemini_chat', args)).run_id, first.run_id);
  assert.equal((await call('ask_gemini_chat', { ...args, mode: 'normal' })).error, 'IDEMPOTENCY_CONFLICT');
  release(); await until(() => service.getRun(first.run_id).status === 'completed');
  const saved = await call('get_gemini_result', { run_id: first.run_id, wait_ms: 0 });
  assert.equal(saved.text, 'reply:one shot'); assert.equal(saved.mode, 'temporary');
  assert.equal((await call('ask_gemini_chat', { ...args, chat_id: first.chat_id, mode: 'normal' })).error, 'CHAT_MODE_MISMATCH');
  const next = await call('ask_gemini_chat', { request_id: 'temporary-2', chat_id: first.chat_id, prompt: 'follow up', wait_ms: 1000 });
  assert.equal(next.mode, 'temporary'); assert.equal(next.status, 'completed');
  assert.deepEqual(backend.generations[1].parent, saved.position);
  assert(backend.generations.every(g => g.temporary));
  backend.failAfterWrite = true;
  const failed = await call('ask_gemini_chat', { request_id: 'temporary-3', chat_id: first.chat_id, prompt: 'interrupted', wait_ms: 1000 });
  assert.equal(failed.status, 'uncertain'); assert.equal(failed.error.code, 'TEMPORARY_RESULT_UNRECOVERABLE');
  const polled = await call('get_gemini_result', { run_id: failed.run_id, wait_ms: 0 });
  assert.equal(polled.status, 'uncertain'); assert.match(polled.next, /Stop polling/);
  assert.equal(backend.generations.length, 3);
});
test('local MCP uploads file bytes once, attaches by ID, and rejects changed or invalid files', async t => {
  const { backend, service } = await setup(t);
  const dir = await mkdtemp(join(tmpdir(), 'agent-file-'));
  const server = createAgentMcpServer(service, { localFiles: true });
  const client = new Client({ name: 'local-agent', version: '1' });
  const [a, b] = InMemoryTransport.createLinkedPair();
  await server.connect(a); await client.connect(b);
  t.after(async () => { await client.close(); await server.close(); await rm(dir, { recursive: true, force: true }); });
  assert.deepEqual((await client.listTools()).tools.map(t => t.name).sort(), ['ask_gemini_chat', 'get_gemini_result', 'upload_gemini_file']);
  const call = async (name: string, args: any) => {
    const r = await client.callTool({ name, arguments: args });
    return JSON.parse((r.content as any[])[0].text);
  };
  const path = join(dir, 'receipt.txt'), content = '仅在附件里出现的回执 🌲';
  await writeFile(path, content);
  let uploads = 0;
  backend.upload = async (bytes, name) => {
    uploads++;
    const data = bytes instanceof Uint8Array ? bytes : await readFile(bytes.path);
    assert.equal(Buffer.from(data).toString(), content);
    return { name, reference: 'uploaded-receipt', size: data.length };
  };
  const args = { request_id: 'upload-1', path };
  const file = await call('upload_gemini_file', args);
  assert.equal(file.size, Buffer.byteLength(content));
  assert.equal((await call('upload_gemini_file', args)).file_id, file.file_id);
  assert.equal(uploads, 1);
  const answer = await call('ask_gemini_chat', { request_id: 'file-question', prompt: 'Read the receipt', mode: 'temporary', file_ids: [file.file_id], wait_ms: 1000 });
  assert.equal(answer.status, 'completed');
  assert.equal(answer.mode, 'temporary'); assert.equal(backend.generations[0].temporary, true);
  assert.equal(backend.generations[0].input.files[0].reference, 'uploaded-receipt');
  await writeFile(path, 'changed');
  assert.equal((await call('upload_gemini_file', args)).error, 'IDEMPOTENCY_CONFLICT');
  await truncate(path, 21 * 1024 * 1024);
  let snapshot = '';
  backend.upload = async (source, name) => {
    assert(!(source instanceof Uint8Array));
    snapshot = source.path;
    assert.equal((await stat(snapshot)).size, 21 * 1024 * 1024);
    return { name, reference: 'large-file', size: source.size };
  };
  const large = await call('upload_gemini_file', { ...args, request_id: 'large' });
  assert.equal(large.size, 21 * 1024 * 1024);
  await assert.rejects(stat(snapshot), { code: 'ENOENT' });
  const many = await call('ask_gemini_chat', { request_id: 'large-input', prompt: 'x'.repeat(120001), file_ids: Array(11).fill(large.file_id), wait_ms: 1000 });
  assert.equal(many.status, 'completed');
  assert.equal(backend.generations.at(-1)!.input.files.length, 11);
  assert.equal((await call('upload_gemini_file', { request_id: 'directory', path: dir })).error, 'INVALID_FILE');
  const relative = await client.callTool({ name: 'upload_gemini_file', arguments: { request_id: 'relative', path: 'receipt.txt' } });
  assert.equal(relative.isError, true);
  assert.equal(uploads, 1);
  const handle = await open(path), prototype = Object.getPrototypeOf(handle);
  await handle.close();
  const original = prototype.createReadStream;
  const changed = t.mock.method(prototype, 'createReadStream', function(this: any, options: any) {
    const stream = original.call(this, options);
    stream.once('data', () => writeFileSync(path, 'changed while copying'));
    return stream;
  });
  assert.equal((await call('upload_gemini_file', { ...args, request_id: 'changed-during-copy' })).error, 'FILE_CHANGED');
  changed.mock.restore();
});
